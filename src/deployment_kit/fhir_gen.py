"""Deterministic locally-generated synthetic FHIR R4 bundle.

Provenance: generated by this module with a fixed seed. These are
NOT Synthea patients and NOT real patients — they are FHIR-format
synthetic records created locally so the validation harness can run
offline. Deliberate defects (a few missing fields / one implausible
date) are planted and counted by the generator so the data-quality
report can be checked against ground truth in tests.
"""
from __future__ import annotations
import json, random
from pathlib import Path

FIRST=["Alex","Maria","James","Priya","Chen","Fatima","Olga","David","Sarah","Kenji"]
LAST=["Nguyen","Garcia","Smith","Patel","Wei","Haddad","Petrova","Johnson","Lee","Tanaka"]
CONDITIONS=[("M54.5","Low back pain"),("E11.9","Type 2 diabetes mellitus"),("I10","Essential hypertension"),("J45.909","Asthma, unspecified"),("M17.0","Bilateral primary osteoarthritis of knee")]
OBS=[("8302-2","Body height","cm"),("9279-1","Respiratory rate","/min"),("8867-4","Heart rate","/min"),("8480-6","Systolic blood pressure","mm[Hg]")]

def generate_bundle(n_patients: int=25, seed: int=42) -> tuple[dict, dict]:
    rng=random.Random(seed); entries=[]; planted={"missing_family_name":0,"implausible_birthdate":0,"missing_condition_code":0}
    def entry(res): return {"fullUrl":f"urn:uuid:{res['resourceType'].lower()}-{res['id']}","resource":res}
    for i in range(1, n_patients+1):
        pid=f"pat-{i:03d}"; first=rng.choice(FIRST); last=rng.choice(LAST)
        patient={"resourceType":"Patient","id":pid,"name":[{"family":last,"given":[first]}],
                 "gender":rng.choice(["male","female"]),"birthDate":f"{rng.randint(1940,2010)}-{rng.randint(1,12):02d}-{rng.randint(1,28):02d}",
                 "identifier":[{"system":"http://example.org/mrn","value":f"MRN{i:06d}"}]}
        if i==3: patient["name"]=[{"given":[first]}]; planted["missing_family_name"]+=1
        if i==7: patient["birthDate"]="1899-01-01"; planted["implausible_birthdate"]+=1
        entries.append(entry(patient))
        entries.append(entry({"resourceType":"Encounter","id":f"enc-{i:03d}","status":"finished",
            "class":{"system":"http://terminology.hl7.org/CodeSystem/v3-ActCode","code":"AMB"},
            "subject":{"reference":f"Patient/{pid}"},"period":{"start":"2026-01-15T09:00:00Z"}}))
        code, display = rng.choice(CONDITIONS)
        cond={"resourceType":"Condition","id":f"cond-{i:03d}","clinicalStatus":{"coding":[{"code":"active"}]},
            "code":{"coding":[{"system":"http://hl7.org/fhir/sid/icd-10-cm","code":code,"display":display}]},
            "subject":{"reference":f"Patient/{pid}"}}
        if i==11: cond["code"]={"coding":[{"system":"http://hl7.org/fhir/sid/icd-10-cm","display":display}]}; planted["missing_condition_code"]+=1
        entries.append(entry(cond))
        loinc, ldisplay, unit = rng.choice(OBS)
        entries.append(entry({"resourceType":"Observation","id":f"obs-{i:03d}","status":"final",
            "code":{"coding":[{"system":"http://loinc.org","code":loinc,"display":ldisplay}]},
            "subject":{"reference":f"Patient/{pid}"},"effectiveDateTime":"2026-01-15T09:05:00Z",
            "valueQuantity":{"value":rng.randint(40,180),"unit":unit}}))
        entries.append(entry({"resourceType":"Claim","id":f"claim-{i:03d}","status":"active","type":{"coding":[{"code":"professional"}]},
            "use":"preauthorization","patient":{"reference":f"Patient/{pid}"},"created":"2026-01-15",
            "insurer":{"display":"Example Payer"},"provider":{"display":"Example Clinic"}}))
    bundle={"resourceType":"Bundle","type":"collection","total":len(entries),"entry":entries}
    return bundle, planted

def write_bundle(path: str|Path, n_patients: int=25, seed: int=42):
    bundle, planted = generate_bundle(n_patients, seed)
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(bundle, indent=2))
    return bundle, planted
